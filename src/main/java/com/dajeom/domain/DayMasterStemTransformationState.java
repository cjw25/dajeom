package com.dajeom.domain;

/**
 * 일간이 직접 참여한 천간오합의
 * 실제 화기 상태.
 *
 * 숫자/확률/점수 없음.
 */
public enum DayMasterStemTransformationState {

    /**
     * 현재 엔진의 엄격한 진화 조건 충족.
     *
     * - 일간이 오합 당사자
     * - 화신이 월령에서 旺
     * - 일간 본래 근 없음
     * - 인성/비겁 생부 없음
     * - 독합
     * - 상대가 월간 또는 시간
     */
    TRUE_TRANSFORMATION,

    /**
     * 화하려는 구조는 존재하지만
     * 진화 조건에 흠이 있음.
     *
     * 예:
     *
     * - 일간 근이 남음
     * - 인성/비겁 생부가 남음
     * - 화신이 월령을 완전히 얻지 못함
     *
     * 원국 오합 자체는 살아 있으므로
     * 단순 不化와 구분한다.
     */
    FAKE_TRANSFORMATION,

    /**
     * 오합 관계는 있으나
     * 현재 엔진에서 화기격 작용을
     * 인정하지 않는 상태.
     */
    NOT_TRANSFORMED,

    /**
     * 동일 일간을 두 개 이상의
     * 합 상대가 동시에 당기는 구조.
     *
     * 쟁합 Context이므로
     * 진화/가화를 확정하지 않는다.
     */
    CONTESTED
}