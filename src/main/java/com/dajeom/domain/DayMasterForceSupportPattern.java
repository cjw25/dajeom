package com.dajeom.domain;

/**
 * 일간을 직접 생조하는
 * 천간의 드러난 형태.
 *
 * 得勢 영역의 핵심 원형 자료다.
 *
 * =================================================
 *
 * GENERATING
 *
 * → 다른 오행이 일간을 생함
 * → 오행 관계상 인성 방향
 *
 * SAME_ELEMENT
 *
 * → 일간과 같은 오행
 * → 오행 관계상 비겁 방향
 *
 * =================================================
 *
 * 이 enum은:
 *
 * - 신강
 * - 신약
 * - 득세 확정
 *
 * 을 뜻하지 않는다.
 *
 * 숫자나 개수도 사용하지 않는다.
 */
public enum DayMasterForceSupportPattern {

    /**
     * 천간에 일간을 생하는 오행도,
     * 같은 오행도 드러나 있지 않음.
     */
    NO_VISIBLE_SUPPORT,

    /**
     * 일간을 생하는 천간은 존재하지만
     * 같은 오행 천간은 없음.
     */
    GENERATING_ONLY,

    /**
     * 같은 오행 천간은 존재하지만
     * 일간을 생하는 천간은 없음.
     */
    SAME_ELEMENT_ONLY,

    /**
     * 일간을 생하는 천간과
     * 같은 오행 천간이 모두 드러남.
     */
    GENERATING_AND_SAME_ELEMENT
}