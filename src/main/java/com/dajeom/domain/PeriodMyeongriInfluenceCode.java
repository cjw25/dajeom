package com.dajeom.domain;

/**
 * 대운 / 세운 / 월운 계산기가 만들어낸 결과를
 * LifeClaim 계층으로 넘기기 전에 정규화한 내부 명리 영향 코드.
 *
 * =================================================
 *
 * 이 계층이 필요한 이유
 * =================================================
 *
 * 기존 운 계산기는:
 *
 * - 천간
 * - 지지
 * - 십성
 * - 합
 * - 충
 * - 형
 * - 원국과의 관계
 *
 * 등을 계산한다.
 *
 * 하지만 LifeClaim 계층이
 * 기존 대운/세운 클래스 구조에 직접 의존하면
 * 운 계산기 구조가 바뀔 때 LifeClaim 계층까지 같이 깨진다.
 *
 * 따라서:
 *
 * 기존 운 계산기
 *      ↓
 * PeriodMyeongriInfluence
 *      ↓
 * PeriodLifeSignal
 *      ↓
 * PeriodLifeClaim
 *
 * 으로 한 번 끊는다.
 *
 * =================================================
 *
 * 이 enum은 사용자에게 노출하지 않는다.
 *
 * 또한 실제 사건을 뜻하지 않는다.
 */
public enum PeriodMyeongriInfluenceCode {

    /*
     * =================================================
     * 印 / 지원·준비
     * =================================================
     */

    /**
     * 해당 기간에 印 계열 작동이 강화되거나
     * 새롭게 활성화되는 구조.
     */
    RESOURCE_ACTIVATED,

    /**
     * 원국에서 사용하던 印/지원 경로가
     * 해당 기간에 약해지거나 방해받는 구조.
     *
     * 단순히 印이 안 들어왔다는 이유로 생성하면 안 된다.
     * 실제 약화 근거가 있을 때만 사용한다.
     */
    RESOURCE_WEAKENED,

    /*
     * =================================================
     * 食傷 / 표현·생산
     * =================================================
     */

    /**
     * 食神/傷官 계열의 표현·생산·출력 경로가 활성화.
     */
    OUTPUT_ACTIVATED,

    /*
     * =================================================
     * 財 / 현실 결과·자원
     * =================================================
     */

    /**
     * 財 계열이 활성화되어
     * 현실 결과·자원 배분·성과 요구가 커지는 구조.
     */
    WEALTH_ACTIVATED,

    /*
     * =================================================
     * 官殺 / 책임·평가
     * =================================================
     */

    /**
     * 官殺 계열이 활성화되어
     * 책임·평가·규칙·압박이 중요해지는 구조.
     */
    AUTHORITY_ACTIVATED,

    /*
     * =================================================
     * 比劫 / 경쟁·독립
     * =================================================
     */

    /**
     * 比肩/劫財 계열이 활성화되어
     * 자기 결정권·동료 관계·경쟁 구조가 중요해짐.
     */
    COMPANION_ACTIVATED,

    /*
     * =================================================
     * 원국 구조 교란
     * =================================================
     */

    /**
     * 운의 지지/천간 작용으로
     * 원국 핵심 구조의 충돌·교란이 실제 활성화.
     *
     * 단순 충 하나가 있다는 이유만으로 생성하면 안 되고
     * 원국의 의미 있는 구조를 건드리는 경우에 사용한다.
     */
    NATAL_STRUCTURE_DISRUPTION_ACTIVATED,

    /**
     * 활성화된 구조 교란에
     * 합 등의 실제 해소 경로가 함께 성립.
     */
    NATAL_STRUCTURE_DISRUPTION_RESOLVED,

    /*
     * =================================================
     * 天干合 등 결속
     * =================================================
     */

    /**
     * 운과 원국 또는 운 내부에서
     * 실제 사용 가능한 강한 결속 작용이 활성화.
     *
     * raw 五合 존재만으로 만들지 않는다.
     */
    ACTIVE_BINDING_ESTABLISHED,

    /*
     * =================================================
     * 원국 중심 방향
     * =================================================
     */

    /**
     * 원국에서 이미 확정된 중심 구조와
     * 같은 방향의 작동이 운에서 강화됨.
     */
    NATAL_DIRECTION_REINFORCED,

    /**
     * 원국에서 확정된 중심 구조가
     * 운의 작용으로 조정 필요 상태가 됨.
     */
    NATAL_DIRECTION_CHALLENGED
}