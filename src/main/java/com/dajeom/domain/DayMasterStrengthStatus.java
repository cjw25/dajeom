package com.dajeom.domain;

/**
 * 일반적인 일간 왕쇠 판정 상태.
 *
 * 숫자 점수에 의해 결정되지 않는다.
 *
 * =================================================
 *
 * SPECIAL_STRUCTURE_REVIEW
 *
 * 종격 등 특수구조 후보가 있어
 * 일반 신강/신약 판정을 먼저 하면 안 되는 상태.
 *
 * =================================================
 *
 * CLEARLY_WEAK
 *
 * 일반 왕쇠 논리 안에서
 * 약한 구조가 명백한 경우.
 *
 * =================================================
 *
 * WEAK_LEANING
 *
 * 약한 방향이 분명하지만
 * 생부나 다른 구조가 남아 있어
 * 극단적인 약으로 확정하지 않는 경우.
 *
 * =================================================
 *
 * MIXED_NEEDS_REVIEW
 *
 * 월령, 근, 생부, 극설 구조가 서로 엇갈려
 * 단순 강/약으로 축약하면 안 되는 경우.
 *
 * =================================================
 *
 * STRONG_LEANING
 *
 * 강한 방향이 분명하지만
 * 극왕으로 확정할 정도의 순수 구조는 아닌 경우.
 *
 * =================================================
 *
 * CLEARLY_STRONG
 *
 * 일반 왕쇠 논리 안에서
 * 강한 구조가 명백한 경우.
 */
public enum DayMasterStrengthStatus {

    SPECIAL_STRUCTURE_REVIEW,

    CLEARLY_WEAK,

    WEAK_LEANING,

    MIXED_NEEDS_REVIEW,

    STRONG_LEANING,

    CLEARLY_STRONG
}