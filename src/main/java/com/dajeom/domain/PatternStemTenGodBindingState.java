package com.dajeom.domain;

/**
 * 하나의 십성이 투출 천간에서
 * active 天干合에 의해 어느 정도 묶였는지 나타낸다.
 *
 * =================================================
 *
 * ABSENT
 *
 * 해당 십성이 천간에 투출되어 있지 않음.
 *
 * =================================================
 *
 * RETAINED
 *
 * 투출되어 있으나
 * active 비일간 합에 묶이지 않음.
 *
 * =================================================
 *
 * PARTIALLY_BOUND
 *
 * 같은 십성이 둘 이상 투출되어 있고
 * 일부만 active 합에 묶임.
 *
 * 예:
 *
 * 七殺 A → 합에 묶임
 * 七殺 B → 그대로 남음
 *
 * 이 경우 合殺留官 완료로 보지 않는다.
 *
 * =================================================
 *
 * FULLY_BOUND
 *
 * 투출된 해당 십성 노드가
 * 모두 active 비일간 합에 묶임.
 *
 * =================================================
 *
 * REVIEW_REQUIRED
 *
 * 해당 십성에 爭合/妬合 검토가 걸려 있어
 * 묶였다고 확정할 수 없음.
 *
 * =================================================
 *
 * 주의:
 *
 * FULLY_BOUND라는 이름을 쓰는 이유는
 * 천간이 물리적으로 "사라진다"는 의미의
 * 제거 개념과 구분하기 위해서다.
 */
public enum PatternStemTenGodBindingState {

    ABSENT,

    RETAINED,

    PARTIALLY_BOUND,

    FULLY_BOUND,

    REVIEW_REQUIRED
}