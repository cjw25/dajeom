package com.dajeom.type;

/**
 * 기본성향 Deterministic Judgment의 종류.
 *
 * =================================================
 *
 * CORE_SELF
 *
 * 원국 일간 자기기반과
 * 확정 신강·신약 구조.
 *
 * =================================================
 *
 * FUNCTION
 *
 * 비겁 / 인성 / 식상 / 재성 / 관살
 * 기능축 자체에 대한 판정.
 *
 * =================================================
 *
 * SITUATION
 *
 * 전통 복합 Pattern에서 확인된
 * 조건부 기능작동에 대한 판정.
 *
 * =================================================
 *
 * INTERPERSONAL_CONTEXT
 *
 * 원국 관계/합화 구조.
 *
 * 이 단계에서는
 * 관계 사실을 행동심리로
 * 확대해석하지 않는다.
 */
public enum PersonalityJudgmentKind {

    CORE_SELF,

    FUNCTION,

    SITUATION,

    INTERPERSONAL_CONTEXT
}